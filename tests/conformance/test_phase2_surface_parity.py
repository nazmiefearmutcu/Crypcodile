# The fixture was generated with these same functions, so the frozen side and the live side
# cannot disagree about what "a command" or "a route" is. Parsing rather than importing is
# the point: an import-time registry is exactly what Phase 2 replaces, and an inventory
# derived from it would move whenever it moves.


def _literal(node: ast.AST | None) -> Any:
    """The default as data where it is data, and as source text where it is not."""
    if node is None:
        return _REQUIRED
    try:
        value = ast.literal_eval(node)
    except Exception:
        return ast.unparse(node)
    if isinstance(value, (str, int, float, bool, dict)) or value is None:
        return value
    if isinstance(value, (list, tuple)):
        return list(value)
    return ast.unparse(node)


def _annotation_name(node: ast.AST | None) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def _defaults(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> dict[str, ast.AST | None]:
    out: dict[str, ast.AST | None] = {}
    positional = fn.args.posonlyargs + fn.args.args
    pad = len(positional) - len(fn.args.defaults)
    for i, arg in enumerate(positional):
        out[arg.arg] = fn.args.defaults[i - pad] if i >= pad else None
    for arg, default in zip(fn.args.kwonlyargs, fn.args.kw_defaults, strict=True):
        out[arg.arg] = default
    return out


def _all_args(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> list[ast.arg]:
    return fn.args.posonlyargs + fn.args.args + fn.args.kwonlyargs


def _typer_option(node: ast.AST | None, aliases: dict[str, ast.AST]) -> ast.Call | None:
    """The ``typer.Option(...)`` governing a parameter, resolving module-level Annotated aliases.

    Both CLIs hoist ``--data-dir`` into a shared ``_DataDirOpt`` alias, so a scan that only
    looked at inline annotations would miss the most widely used option in the product.
    """
    if isinstance(node, ast.Name) and node.id in aliases:
        node = aliases[node.id]
    if isinstance(node, ast.Subscript) and _annotation_name(node.value) == "Annotated":
        elements = node.slice.elts if isinstance(node.slice, ast.Tuple) else [node.slice]
        for element in elements[1:]:
            if isinstance(element, ast.Call):
                func = element.func
                if (isinstance(func, ast.Attribute) and func.attr == "Option") or (
                    isinstance(func, ast.Name) and func.id == "Option"
                ):
                    return element
    return None


def _flags(option: ast.Call) -> list[str]:
    """Every long spelling declared on one option.

    Typer allows several, either as separate strings (``"--expiry-ns", "--expiry"``) or as a
    boolean pair in one (``"--persist/--no-persist"``). All of them are on the wire.
    """
    out: list[str] = []
    for arg in option.args:
        value = _literal(arg)
        if isinstance(value, str) and value.startswith("-"):
            out.extend(part for part in value.split("/") if part.startswith("--"))
    return out


def scan_cli(path: pathlib.Path) -> dict[str, dict[str, Any]]:
    """Typer command name → its long options and their defaults."""
    tree = ast.parse(path.read_text())
    aliases = {
        node.targets[0].id: node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name)
        and isinstance(node.value, ast.Subscript)
    }

    out: dict[str, dict[str, Any]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        command: str | None = None
        for decorator in node.decorator_list:
            if isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Attribute):
                if decorator.func.attr == "command":
                    named = next(
                        (_literal(k.value) for k in decorator.keywords if k.arg == "name"), None
                    )
                    # typer.main.get_command_name: lowercase, underscores to dashes.
                    command = (
                        named if isinstance(named, str) else node.name.lower().replace("_", "-")
                    )
            elif isinstance(decorator, ast.Attribute) and decorator.attr == "command":
                command = node.name.lower().replace("_", "-")
        if command is None:
            continue

        defaults = _defaults(node)
        options: dict[str, Any] = {}
        for arg in _all_args(node):
            option = _typer_option(arg.annotation, aliases)
            default = defaults.get(arg.arg)
            if option is None:
                # The pre-Annotated spelling: ``name: T = typer.Option(default, "--flag")``.
                if (
                    isinstance(default, ast.Call)
                    and isinstance(default.func, ast.Attribute)
                    and default.func.attr == "Option"
                ):
                    option = default
                    positional = option.args[0] if option.args else None
                    literal = _literal(positional) if positional is not None else None
                    default = (
                        positional
                        if not (isinstance(literal, str) and literal.startswith("-"))
                        else None
                    )
                else:
                    continue  # a typer.Argument, or a plain parameter: not an option
            for flag in _flags(option) or ["--" + arg.arg.replace("_", "-")]:
                options[flag] = _literal(default)
        out[command] = {"options": dict(sorted(options.items()))}
    return out


def scan_rest(path: pathlib.Path) -> dict[str, dict[str, Any]]:
    """``METHOD /path`` → its query, header and body parameters with defaults."""
    tree = ast.parse(path.read_text())
    models: dict[str, dict[str, Any]] = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and any(
            _annotation_name(base) == "BaseModel" for base in node.bases
        ):
            models[node.name] = {
                stmt.target.id: _literal(stmt.value)
                for stmt in node.body
                if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)
            }

    out: dict[str, dict[str, Any]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not (
                isinstance(decorator, ast.Call)
                and isinstance(decorator.func, ast.Attribute)
                and decorator.func.attr in {"get", "post", "put", "delete", "patch"}
                and decorator.args
            ):
                continue
            defaults = _defaults(node)
            params: dict[str, Any] = {}
            for arg in _all_args(node):
                annotation = _annotation_name(arg.annotation)
                if annotation in _INJECTED:
                    continue
                if annotation in models:
                    params.update(models[annotation])  # a POST body is its model's fields
                    continue
                default = defaults.get(arg.arg)
                name = arg.arg
                if (
                    isinstance(default, ast.Call)
                    and isinstance(default.func, ast.Name)
                    and default.func.id in {"Query", "Header", "Body", "Path", "Form"}
                ):
                    alias = next(
                        (_literal(k.value) for k in default.keywords if k.arg == "alias"), None
                    )
                    if isinstance(alias, str):
                        name = alias  # the header's wire spelling, not the Python one
                    inner = next(
                        (k.value for k in default.keywords if k.arg == "default"), None
                    ) or (default.args[0] if default.args else None)
                    params[name] = _literal(inner)
                else:
                    params[name] = _literal(default)
            key = f"{decorator.func.attr.upper()} {_literal(decorator.args[0])}"
            out[key] = {"params": dict(sorted(params.items()))}
    return out


def scan_mcp(path: pathlib.Path) -> dict[str, dict[str, Any]]:
    """MCP tool name → its ``inputSchema`` properties and their defaults."""
    out: dict[str, dict[str, Any]] = {}
    for node in ast.parse(path.read_text()).body:
        if not (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "TOOLS"
        ):
            continue
        for element in node.value.elts:
            tool = ast.literal_eval(element)
            schema = tool.get("inputSchema") or {}
            required = set(schema.get("required") or ())
            properties = schema.get("properties") or {}
            out[tool["name"]] = {
                "params": {
                    name: body.get("default", _REQUIRED if name in required else None)
                    for name, body in sorted(properties.items())
                }
            }
    return out


_SCANNERS = {"cli": scan_cli, "rest": scan_rest, "mcp": scan_mcp}


