def test_the_frozen_surface_is_the_size_it_should_be() -> None:
    """An emptied or truncated fixture would pass every assertion below in silence.

    That is not hypothetical here: two AST gates earlier in this merge went green while
    checking an empty tree. The counts are pinned so that deleting entries to make the gate
    pass fails first, loudly, and names the file it happened to.
    """
    frozen = _frozen()
    assert set(frozen) == {"crypto", "equity"}
    assert {k for kinds in frozen.values() for k in kinds} == {"cli", "rest", "mcp"}

    counts = {(f, k): len(e) for f, kinds in frozen.items() for k, e in kinds.items()}
    assert counts == {
        ("crypto", "cli"): 48,
        ("crypto", "rest"): 48,
        ("crypto", "mcp"): 37,
        ("equity", "cli"): 9,
        ("equity", "rest"): 9,
        ("equity", "mcp"): 5,
    }, f"the six legacy surfaces exposed these counts; found {counts}"

    total = sum(len(params) for *_, params in _frozen_entries())
    assert total == 456, f"the six surfaces declared 456 parameters between them, found {total}"


def test_the_scanners_still_find_the_surfaces_they_are_pointed_at() -> None:
    """A scanner that silently returns nothing is a served-side hole, not a red test.

    While a legacy file is still on disk it must still parse into entries. If it stopped —
    renamed, moved, or a decorator spelling the scan does not recognise — ``_served()`` would
    quietly shrink and the parity assertions would start reporting losses that never
    happened, or worse, the exemption tests would start passing for the wrong reason.
    """
    for (fork, kind), path in _LEGACY.items():
        if path.exists():
            assert _SCANNERS[kind](path), f"{fork}.{kind} exists at {path} but scanned to nothing"


